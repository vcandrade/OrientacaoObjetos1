package aula08.classesnativas.string;

public class Exemplo07ToLowerCase {

	public static void main(String[] args) {

		String universidade = "Universidade Tecnológica Federal do Paraná";

		String letrasMinusculas = universidade.toLowerCase();

		System.out.println(universidade);
		System.out.println(letrasMinusculas);
	}
}
