package aula08.classesnativas.string;

public class Exemplo08ToUpperCase {

	public static void main(String[] args) {

		String universidade = "Universidade Tecnológica Federal do Paraná";

		String letrasMaiusculas = universidade.toUpperCase();

		System.out.println(universidade);
		System.out.println(letrasMaiusculas);
	}
}
